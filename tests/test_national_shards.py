"""National shard lazy-loading checks. Serves the repo with a sample shards/ directory (real fetched shards
of NON-core stores, generated by scripts/sync_stores.py --shards). Never modifies a retailer cart."""
import http.server, json, shutil, socketserver, threading, sys
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
SAMPLE = "super-sapir::130"  # a national (non-core) store with a fetched shard in ./shards/
if not (ROOT / "shards" / (SAMPLE.replace("::", "--") + ".json")).exists():
    print("SKIP: sample shard not present; generate with --shards before running this test")
    sys.exit(0)


class H(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *a, **k):
        super().__init__(*a, directory=str(ROOT), **k)

    def log_message(self, *a):
        pass


srv = socketserver.TCPServer(("127.0.0.1", 0), H)
threading.Thread(target=srv.serve_forever, daemon=True).start()
checks = 0
fail = []


def check(label, condition, details=None):
    global checks
    checks += 1
    print(("PASS " if condition else "FAIL ") + label + ((" " + str(details)) if not condition else ""))
    if not condition:
        fail.append(label)


with sync_playwright() as p:
    b = p.chromium.launch(executable_path=shutil.which("google-chrome") or shutil.which("chromium"), args=["--no-sandbox"])
    for tag, width in [("desktop", 1280), ("mobile", 390)]:
        pg = b.new_page(viewport={"width": width, "height": 900 if width > 400 else 844})
        errors = []
        pg.on("pageerror", lambda e: errors.append(str(e)))
        pg.goto("http://127.0.0.1:%d/index.html" % srv.server_address[1])
        pg.wait_for_function("state.livePricesLoaded && Object.keys(STORE_DIRECTORY.stores).length>500")

        check(tag + " shard index loaded at boot", pg.evaluate("Object.keys(SHARD_INDEX.stores).length") >= 1,
              pg.evaluate("JSON.stringify(SHARD_INDEX.stores)"))
        check(tag + " national store NOT loaded until selected",
              pg.evaluate("!state.livePrices.metadata.chains['%s']" % SAMPLE))
        check(tag + " directory row offers live prices for national store",
              pg.evaluate(
                  "(()=>{const s=STORE_DIRECTORY.stores['%s'];return !!s && !!SHARD_INDEX.stores['%s'] && SHARD_INDEX.stores['%s'].status==='ok';})()"
                  % (SAMPLE, SAMPLE, SAMPLE)))

        pg.evaluate("switchTab('Cart')")
        pg.evaluate("chooseDirectoryStore('%s')" % SAMPLE)
        pg.wait_for_function("!!(state.livePrices.metadata.chains['%s'])" % SAMPLE, timeout=15000)
        priced = pg.evaluate("state.chainPriced['%s'] || 0" % SAMPLE)
        check(tag + " shard lazy-loaded and merged on selection", priced > 0, priced)
        check(tag + " national store marked fresh+published", pg.evaluate("!!state.chainFresh['%s']" % SAMPLE))
        check(tag + " shard self-describes promos as not collected",
              pg.evaluate("(state.livePrices.promotions['%s']||{}).status" % SAMPLE) == "not-collected")
        check(tag + " national store in compare selection", pg.evaluate("getCompareSelection().includes('%s')" % SAMPLE))
        title_ok = pg.evaluate(
            "(()=>{const c=[...document.querySelectorAll('#supermarketPriceGrid > div')];return c.some(d=>d.textContent.includes('%s'));})()"
            % "סופר ספיר")
        check(tag + " comparison card shows chain name for national store", title_ok)

        pg.reload()
        pg.wait_for_function("state.livePricesLoaded")
        pg.wait_for_function("!!(state.livePrices.metadata.chains['%s'])" % SAMPLE, timeout=15000)
        check(tag + " saved selection reloads its shard after full page reload", True)

        pg.evaluate("setCompareSelection(getCompareSelection().filter(k=>k!=='%s'))" % SAMPLE)
        check(tag + " national store can be unticked", pg.evaluate("!getCompareSelection().includes('%s')" % SAMPLE))

        check(tag + " no JavaScript errors", not errors, errors[:3])
        pg.close()
    b.close()
print("SHARD UI CHECKS", checks, "FAILURES", len(fail))
sys.exit(1 if fail else 0)
